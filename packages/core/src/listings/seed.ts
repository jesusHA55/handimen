const daysAgo = (days: number): string =>
  new Date(Date.now() - days * 24 * 60 * 60 * 1000).toISOString();

function listing(
  partial: Omit<Listing, "cityId" | "groupId" | "status" | "createdAt" | "photos"> & {
    days: number;
    photos?: string[];
    groupId?: string | null;
  },
): Listing {
  const { days, photos, groupId, ...rest } = partial;
  return {
    ...rest,
    photos: photos ?? [rest.type === "skill" || rest.type === "service" ? "🧰" : "🔧"],
    cityId: POBLENOU_CITY_ID,
    groupId: groupId ?? null,
    status: "active",
    createdAt: daysAgo(days),
  };
}

